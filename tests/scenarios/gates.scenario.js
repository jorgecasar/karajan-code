// KJC-TSK-1022 (QS-A): the Sentinel's gates, together, on a freshly hardened
// project. Each case is a bug that reached a user (KJC-BUG-0333, 0338, 0340).
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { makeScenarioProject } from "./helpers/scenario-project.js";

let p;
beforeAll(() => {
  p = makeScenarioProject();
  const res = p.kj("harden");
  if (res.status !== 0) throw new Error(`kj harden failed: ${res.stderr || res.stdout}`);
  // A real clone declares its identity; gh commands then carry the account.
  const id = p.kj("identity", "set", "--gh", "scenario", "--email", "scenario@test.local");
  if (id.status !== 0) throw new Error(`kj identity set failed: ${id.stderr || id.stdout}`);
}, 300_000);
afterAll(() => p?.cleanup());

describe("scenario: a hardened project's read-only chains pass the gates", () => {
  it("a kj rag query whose quoted text mentions publishing is not a publish (0333)", () => {
    const r = p.bash("kj rag query --no-rag-update 'how does npm publish work in the release flow'");
    expect(r.status, r.stderr).toBe(0);
  });

  it("a quoted question naming a path is a read for the lane guard (0338)", () => {
    const r = p.bash("kj rag query 'what does src/pricing page.js do'");
    expect(r.status, r.stderr).toBe(0);
  });

  it("a real publish is still seen as one", () => {
    const r = p.bash("npm publish --otp=000000");
    expect(r.status).toBe(2);
    expect(r.stderr).toMatch(/release check/);
  });

  it("a body file under a dir named after a model is not an attribution (0340)", () => {
    const dir = path.join(p.root, "claude-1000");
    fs.mkdirSync(dir, { recursive: true });
    const body = path.join(dir, "pr.md");
    fs.writeFileSync(body, "Contract regenerated.\n");
    const r = p.bash(`gh auth switch --user scenario && gh pr create --title 'chore(kj): contract generated by kj' --body-file ${body}`);
    expect(r.status, r.stderr).toBe(0);
  });
});
